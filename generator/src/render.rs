/// `skills/origin/references/{service}.md`.
pub fn origin(inputs: &Inputs, service: &Service, problems: &mut Problems) -> String {
    let tree = inputs.cli;
    let by_method = tree.by_method();
    let version = &inputs.clients.cli.version;
    let current = inputs.current(tree.api_revision.as_deref());
    let command_of = |m: &Method| -> Option<&cli::Command> { by_method.get(&m.full_name).copied() };

    let mut out = inputs.header(&format!("origin {version}"));
    out.push_str(&title(service));
    out.push_str(&inputs.docs_line(service));
    let _ = writeln!(
        out,
        "Commands: `origin {} <command>`. Add `--output json` to every command whose output you read.\n",
        service.name
    );
    out.push_str(&about(service));
    out.push_str(&ask_first(
        service,
        |m| command_of(m).map(|c| format!("`origin {}`", c.path.join(" "))),
        // The flag of a request field, when the command has one by its
        // name; the field's path otherwise.
        |m, path| {
            let flag = path.rsplit('.').next().unwrap_or(path).replace('_', "-");
            match command_of(m) {
                Some(c) if tree.has_flag(c, &flag) => format!("--{flag}"),
                _ => path.to_owned(),
            }
        },
    ));

    out.push_str("## Commands\n\n");
    let mut missing = Vec::new();
    for i in &service.interfaces {
        for m in &i.methods {
            let Some(c) = command_of(m) else {
                if current && m.no_tool.is_none() {
                    problems.push(format!(
                        "origin {version} has no command for {}",
                        m.full_name
                    ));
                }
                missing.push(m);
                continue;
            };
            let _ = writeln!(out, "### `origin {}`\n", c.path.join(" "));
            let _ = writeln!(out, "{}\n", first_sentence(&m.about));
            let mut usage = format!("origin {}", c.path.join(" "));
            for a in c.args.iter().filter(|a| a.required && !a.global) {
                let _ = write!(usage, " {}", a.usage());
            }
            let _ = writeln!(out, "```sh\n{usage}\n```\n");
            let optional: Vec<&cli::Arg> =
                c.args.iter().filter(|a| !a.required && !a.global).collect();
            if !optional.is_empty() {
                let flags: Vec<String> = optional
                    .iter()
                    .map(|a| format!("`{}`", a.usage()))
                    .collect();
                let _ = writeln!(out, "Also: {}", flags.join(", "));
            }
            let mut notes = method_notes(m, true);
            if m.destructive() {
                notes
                    .push("refuses without `--yes`; pass it only after the user agreed".to_owned());
            }
            if !optional.is_empty() && !notes.is_empty() {
                out.push('\n');
            }
            for n in notes {
                let _ = writeln!(out, "- {n}");
            }
            out.push('\n');
        }
    }
    if service.operations {
        let get = by_method.get(&format!("{}:GetOperation", service.name));
        let wait = by_method.get(&format!("{}:WaitOperation", service.name));
        if let (Some(get), Some(wait)) = (get, wait) {
            let _ = writeln!(
                out,
                "### Operations\n\n`origin {}` reads an operation, `origin {}` waits for it: \
                 give the operation's `name` exactly as the command printed it.\n",
                get.path.join(" "),
                wait.path.join(" ")
            );
        }
    }
    if !missing.is_empty() {
        let _ = writeln!(out, "## Not in origin {version}\n");
        for m in missing {
            let reason = m.no_tool.as_deref().unwrap_or("not in this release");
            let _ = writeln!(out, "- `{}`: {}", m.name, reason);
        }
        out.push('\n');
    }
    out.push_str(&resources(service));
    out
}

