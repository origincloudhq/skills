/// `skills/origincloud-terraform/references/{service}.md`.
pub fn terraform(inputs: &Inputs, service: &Service, problems: &mut Problems) -> String {
    let provider = inputs.terraform;
    let pin = &inputs.clients.terraform;
    let current = inputs.current(inputs.terraform_api_revision);
    let shortcode = service.host.split('.').next().unwrap_or(&service.name);
    let by_method = inputs.cli.by_method();

    let mut out = inputs.header(&format!("{} {}", pin.source, pin.version));
    out.push_str(&title(service));
    out.push_str(&inputs.docs_line(service));
    out.push('\n');
    out.push_str(&about(service));

    let mut managed_any = false;
    let mut types = String::from("## Types\n\n");
    for r in &service.resources {
        let singular = format!("origincloud_{shortcode}_{}", r.singular.to_snake_case());
        let plural = format!("origincloud_{shortcode}_{}", r.plural.to_snake_case());
        let resource = provider.resource_schemas.get(&singular);
        let data = provider.data_source_schemas.get(&singular);
        let list = provider.data_source_schemas.get(&plural);
        if resource.is_none() && data.is_none() && list.is_none() {
            continue;
        }
        managed_any = true;
        let _ = writeln!(types, "### {}\n", r.message);
        if !r.about.is_empty() {
            let _ = writeln!(types, "{}\n", first_sentence(&r.about));
        }
        if resource.is_some() {
            let _ = writeln!(types, "- resource `{singular}`");
        }
        if data.is_some() {
            let _ = writeln!(types, "- data source `{singular}`: one by its name");
        }
        if list.is_some() {
            let _ = writeln!(types, "- data source `{plural}`: every one under a parent");
        }
        if let (Some(_), Some(pattern)) = (resource, r.patterns.first()) {
            let _ = writeln!(
                types,
                "- import by `name`:\n\n  ```hcl\n  import {{\n    to = {singular}.this\n    id = \"{pattern}\"\n  }}\n  ```"
            );
        }
        types.push('\n');
        if let Some(schema) = resource.or(data) {
            let kind = if resource.is_some() {
                "Arguments and attributes"
            } else {
                "Attributes"
            };
            let _ = writeln!(types, "{kind} of `{singular}`:\n");
            types.push_str("| Name | Mode | About |\n|---|---|---|\n");
            for (name, a) in &schema.block.attributes {
                let mut mode = a.mode().to_owned();
                if a.replaces() {
                    mode.push_str(", replaces");
                }
                if a.sensitive {
                    mode.push_str(", sensitive");
                }
                let _ = writeln!(
                    types,
                    "| `{name}` | {mode} | {} |",
                    cell(first_sentence(&a.description))
                );
            }
            for (name, b) in &schema.block.block_types {
                let _ = writeln!(
                    types,
                    "| `{name}` | block ({}) | {} |",
                    b.nesting_mode,
                    cell(first_sentence(&b.block.description))
                );
            }
            types.push('\n');
        }
    }
    if managed_any {
        out.push_str(&ask_first(
            service,
            |m| {
                m.resource.as_ref().and_then(|t| {
                    let r = service.resources.iter().find(|r| &r.type_name == t)?;
                    let name = format!("origincloud_{shortcode}_{}", r.singular.to_snake_case());
                    provider.resource_schemas.contains_key(&name).then(|| {
                        if m.delete {
                            format!("`{name}` destroyed or replaced")
                        } else {
                            format!("`{name}`")
                        }
                    })
                })
            },
            // A path from the request, `volume.size_gib`, is the
            // resource's argument `size_gib`.
            |_, path| {
                path.split_once('.')
                    .map_or(path, |(_, rest)| rest)
                    .to_owned()
            },
        ));
        out.push_str(&types);
    } else {
        let _ = writeln!(
            out,
            "{} {} has no resource or data source of this service.\n",
            pin.source, pin.version
        );
        if current && service.resources.iter().any(|r| !r.patterns.is_empty()) {
            problems.push(format!(
                "{} {} has no type for any resource of {}",
                pin.source, pin.version, service.name
            ));
        }
    }

    // What the provider doesn't manage: the custom methods, which the CLI
    // and the SDKs call.
    let custom: Vec<&Method> = methods(service)
        .filter(|m| m.kind == Kind2::Custom)
        .collect();
    if !custom.is_empty() {
        out.push_str(
            "## Other actions\n\nThese methods aren't a resource's create, read, update or delete. \
             Where an argument of a resource above sets the same thing (a resource's `protected`, \
             say), change the argument; otherwise the provider doesn't manage the action: run it \
             with the CLI, outside of Terraform, when the user asks for it.\n\n",
        );
        for m in custom {
            let command = by_method
                .get(&m.full_name)
                .map(|c| format!(" (`origin {}`)", c.path.join(" ")))
                .unwrap_or_default();
            let _ = writeln!(
                out,
                "- `{}`{command}: {}",
                m.name,
                cell(first_sentence(&m.about))
            );
        }
        out.push('\n');
    }
    out
}

