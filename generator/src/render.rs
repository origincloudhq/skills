/// `skills/origincloud-sdk/references/{service}.md`.
pub fn sdk(inputs: &Inputs, service: &Service, problems: &mut Problems) -> String {
    let versions: Vec<String> = LANGUAGES
        .iter()
        .filter_map(|l| {
            inputs
                .sdks
                .get(l)
                .map(|r| format!("sdk-{} {}", l.key(), r.version))
        })
        .collect();
    let mut out = inputs.header(&versions.join(", "));
    out.push_str(&title(service));
    out.push_str(&inputs.docs_line(service));
    out.push('\n');
    out.push_str(&about(service));

    out.push_str("## Packages\n\n| Language | Install | Import |\n|---|---|---|\n");
    for l in LANGUAGES {
        let Some(release) = inputs.sdks.get(&l) else {
            continue;
        };
        let install = match l {
            Language::Rust => format!(
                "`cargo add {}@{}`",
                l.package(&service.name),
                release.version
            ),
            Language::Go => format!("`go get {}@v{}`", l.package(&service.name), release.version),
            Language::TypeScript => format!(
                "`npm install @origincloud/core@{v} {}@{v}`",
                l.package(&service.name),
                v = release.version
            ),
        };
        let import = match l {
            Language::Go => format!(
                "`{}` (package `{}{}`)",
                l.module(&service.name, &service.version),
                service.name,
                service.version
            ),
            _ => format!("`{}`", l.module(&service.name, &service.version)),
        };
        let _ = writeln!(out, "| {} | {install} | {import} |", l.title());
    }
    out.push('\n');

    out.push_str(&ask_first(service, |_| None, |_, path| path.to_owned()));

    for i in &service.interfaces {
        let _ = writeln!(out, "## {}\n", i.name);
        if !i.about.is_empty() {
            let _ = writeln!(out, "{}\n", first_sentence(&i.about));
        }
        out.push_str("| Language | Client |\n|---|---|\n");
        for l in LANGUAGES {
            let _ = writeln!(
                out,
                "| {} | `{}` |",
                l.title(),
                l.constructor(&service.name, &service.version, &i.name)
            );
        }
        out.push('\n');
        out.push_str("| RPC | Rust | Go | TypeScript | Notes |\n|---|---|---|---|---|\n");
        for m in &i.methods {
            let mut names = Vec::new();
            for l in LANGUAGES {
                let Some(release) = inputs.sdks.get(&l) else {
                    names.push("—".to_owned());
                    continue;
                };
                if release.has(l, &service.name, &i.name, &m.name) {
                    let mut name = format!("`{}`", l.method(&m.name));
                    if let Some((items, json)) = &m.items {
                        let _ = write!(name, ", `{}`", l.all_pages(items, json));
                    }
                    names.push(name);
                } else {
                    if inputs.current(Some(&release.api_revision)) {
                        problems.push(format!(
                            "sdk-{} {} has no `{}` for {}: the naming rule and the SDK differ",
                            l.key(),
                            release.version,
                            l.signature(&i.name, &m.name),
                            m.full_name
                        ));
                    }
                    names.push(format!("not in {}", release.version));
                }
            }
            let _ = writeln!(
                out,
                "| `{}` (`{}`) | {} | {} | {} | {} |",
                m.name,
                m.request,
                names[0],
                names[1],
                names[2],
                cell(&sdk_notes(m))
            );
        }
        out.push('\n');
    }
    out.push_str(
        "Field names: Rust uses the proto names (`size_gib`), Go protoc-gen-go's (`SizeGib`), \
         TypeScript the JSON names (`sizeGib`).\n\n",
    );
    out.push_str(&resources(service));
    out
}

/// A method's cell in the SDK reference's table: its description's first
/// sentence, then its notes, joined with semicolons. A note that ends with
/// a period, as a one-way change's consequence and the reason a method has
/// no MCP tool do, loses it there, so that no `;` follows a period.
fn sdk_notes(m: &Method) -> String {
    let mut notes = method_notes(m, false);
    let required: Vec<String> = m
        .fields
        .iter()
        .filter(|f| f.has(Behavior::Required))
        .map(|f| format!("`{}`", f.name))
        .collect();
    if !required.is_empty() {
        notes.push(format!("requires {}", required.join(", ")));
    }
    let last = notes.len().saturating_sub(1);
    let notes: Vec<&str> = notes
        .iter()
        .enumerate()
        .map(|(i, n)| {
            let n = n.trim_end();
            if i < last {
                n.trim_end_matches('.')
            } else {
                n
            }
        })
        .collect();
    format!("{} {}", first_sentence(&m.about), notes.join("; "))
        .trim()
        .to_owned()
}

