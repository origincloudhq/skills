//! The references of each skill, one file per service of the API, from the
//! resource model in the names of each client: the CLI's commands and
//! flags from its release's command tree, Terraform's types and arguments
//! from the provider's schema, and the SDKs' clients and methods from their
//! generators' naming rules, checked against their releases.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use heck::ToSnakeCase;

use crate::cli;
use crate::docs::first_sentence;
use crate::model::{Behavior, Field, Kind2, Method, Resource, Service};
use crate::pins::{Clients, Docs};
use crate::sdk::{self, Language, LANGUAGES};
use crate::terraform;

/// The skills, by directory under `skills/`.
pub const ORIGIN: &str = "origin";
pub const TERRAFORM: &str = "origincloud-terraform";
pub const SDK: &str = "origincloud-sdk";
pub const SKILLS: [&str; 3] = [ORIGIN, TERRAFORM, SDK];

/// Everything the references are made from.
pub struct Inputs<'a> {
    pub api_revision: &'a str,
    pub clients: &'a Clients,
    pub docs: &'a Docs,
    pub cli: &'a cli::Tree,
    pub terraform: &'a terraform::Provider,
    /// The API commit the provider release was generated from.
    pub terraform_api_revision: Option<&'a str>,
    pub sdks: &'a BTreeMap<Language, sdk::Release>,
}

/// What a client release lacks of the API although it was generated from
/// the pinned revision: a name the naming rules got wrong. Generation fails
/// with them.
pub type Problems = Vec<String>;

impl Inputs<'_> {
    fn short(&self) -> &str {
        &self.api_revision[..12.min(self.api_revision.len())]
    }

    /// Whether `revision` is the pinned API's: then the client must have a
    /// name for every method.
    fn current(&self, revision: Option<&str>) -> bool {
        revision == Some(self.api_revision)
    }

    fn header(&self, client: &str) -> String {
        format!(
            "<!-- Generated by scripts/generate.sh from origincloudhq/api@{} and {client}. \
             Don't edit this file: change the generator, or the API. -->\n",
            self.short()
        )
    }

    fn docs_line(&self, service: &Service) -> String {
        match self.docs.markdown(&service.name) {
            Some(url) => format!("Guide: <{url}>\n"),
            None => String::new(),
        }
    }
}

// ---------------------------------------------------------------- shared

/// A service's title: its name and host.
fn title(service: &Service) -> String {
    format!("# {} ({})\n\n", service.name, service.host)
}

/// What the service's proto services say about themselves.
fn about(service: &Service) -> String {
    let mut out = String::new();
    for i in &service.interfaces {
        if !i.about.is_empty() {
            let _ = writeln!(out, "- **{}**: {}", i.name, first_sentence(&i.about));
        }
    }
    if !out.is_empty() {
        out.push('\n');
    }
    out
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

/// A field's description for a table: its first sentence, its enum values
/// and the resource a reference names.
fn field_about(f: &Field) -> String {
    let mut text = first_sentence(&f.about).to_owned();
    if let Some(r) = &f.reference {
        let _ = write!(text, " Names a `{}`.", r.rsplit('/').next().unwrap_or(r));
    }
    if !f.values.is_empty() {
        let _ = write!(
            text,
            " One of {}.",
            f.values
                .iter()
                .map(|v| format!("`{v}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    if let Some(o) = &f.oneof {
        let _ = write!(text, " One of the oneof `{o}`.");
    }
    cell(text.trim())
}

/// The resource's names and fields, in the API's JSON.
fn resource_section(r: &Resource) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "### {}\n", r.message);
    if !r.about.is_empty() {
        let _ = writeln!(out, "{}\n", first_sentence(&r.about));
    }
    for (pattern, full) in r.patterns.iter().zip(r.full_names()) {
        let _ = writeln!(out, "- Full name: `{full}`");
        let _ = writeln!(out, "- `name`: `{pattern}`");
    }
    out.push('\n');
    out.push_str("| Field (JSON) | Type | Behavior | About |\n|---|---|---|---|\n");
    for f in &r.fields {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            f.json_name,
            cell(&f.type_label),
            f.behavior_label(),
            field_about(f)
        );
    }
    out.push('\n');
    out
}

fn resources(service: &Service) -> String {
    if service.resources.is_empty() {
        return String::new();
    }
    let mut out = String::from("## Resources\n\n");
    for r in &service.resources {
        out.push_str(&resource_section(r));
    }
    out
}

/// The notes every surface gives a method: what to wait for, what to ask
/// before, and what makes a retry safe.
fn method_notes(m: &Method, cli: bool) -> Vec<String> {
    let mut notes = Vec::new();
    if m.delete {
        notes.push("**ask first**: deletes for good".to_owned());
    }
    for (field, consequence) in &m.one_way {
        notes.push(format!(
            "**ask first** when changing `{field}`: {consequence}"
        ));
    }
    match (&m.long_running, cli) {
        (Some(result), true) => notes.push(format!(
            "starts an operation and waits for it, unless `--no-wait`; its result is a `{result}`"
        )),
        (Some(result), false) => notes.push(format!(
            "answers with an operation: wait for it; its result is a `{result}`"
        )),
        _ => {}
    }
    match (m.request_id, cli) {
        (true, true) => notes.push("`--request-id` makes a retry safe".to_owned()),
        (true, false) => notes.push("a retry with the same `request_id` is safe".to_owned()),
        _ => {}
    }
    if let Some(why) = &m.no_tool {
        notes.push(format!("no MCP tool: {why}"));
    }
    notes
}

fn methods(service: &Service) -> impl Iterator<Item = &Method> {
    service.interfaces.iter().flat_map(|i| &i.methods)
}

/// The changes to ask about before making them, for the top of a file.
fn ask_first(
    service: &Service,
    name: impl Fn(&Method) -> Option<String>,
    field: impl Fn(&Method, &str) -> String,
) -> String {
    let destructive: Vec<&Method> = methods(service).filter(|m| m.destructive()).collect();
    if destructive.is_empty() {
        return String::new();
    }
    let mut out = String::from(
        "## Ask before\n\nThese delete something or can't be undone: show the user what will \
         change and wait for their yes.\n\n",
    );
    for m in destructive {
        let label = name(m).unwrap_or_else(|| format!("`{}`", m.name));
        if m.delete {
            let _ = writeln!(out, "- {label}: deletes for good.");
        }
        for (path, consequence) in &m.one_way {
            let _ = writeln!(
                out,
                "- {label}, changing `{}`: {consequence}",
                field(m, path)
            );
        }
    }
    out.push('\n');
    out
}

